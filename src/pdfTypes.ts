export type PdfMode = "single" | "spread" | "scroll";
export type PdfPosition = {
  page: number;
  x?: number;
  y?: number;
  view: Pick<PdfSettings, "mode" | "fit" | "scale" | "rotation" | "translationView">;
};
export type PdfSettings = {
  mode: PdfMode;
  fit: "manual" | "width" | "page";
  scale: number;
  rotation: number;
  brightness: number;
  theme: "paper" | "dark";
  voice: string;
  rate: number;
  translationView?: "original" | "parallel" | "translated";
  formScripts?: boolean;
};
export type PdfAnnotation = {
  id: string;
  subtype: string;
  rect: number[];
  dest?: unknown;
  url?: string;
  action?: string;
  titleObj?: { str?: string };
  contentsObj?: { str?: string };
  fieldName?: string;
  fieldValue?: string | string[] | boolean;
  fieldType?: string;
  alternativeText?: string;
  readOnly?: boolean;
  required?: boolean;
  maxLen?: number;
  multiLine?: boolean;
  password?: boolean;
  checkBox?: boolean;
  radioButton?: boolean;
  pushButton?: boolean;
  exportValue?: string;
  buttonValue?: string;
  combo?: boolean;
  multiSelect?: boolean;
  options?: { exportValue: string; displayValue: string }[];
  creationDate?: string;
  modificationDate?: string;
  file?: PdfAttachment;
};
export type PdfAttachment = {
  filename: string;
  content: Uint8Array;
  description?: string;
};
export type PdfOcrRecord = {
  version: 1;
  page: number;
  text: string;
  language: string;
  created: number;
  words: { text: string; rect: [number, number, number, number] }[];
};
